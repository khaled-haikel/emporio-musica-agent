"""Run the real agent on the example conversations and save transcripts to examples/*.md.

Nothing in examples/ is written by hand: every answer comes from the model and every
tool result from the CSVs. Usage: python scripts/run_examples.py
"""

import json
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from emporio.agent import Agent  # noqa: E402
from emporio.tools import load_tables  # noqa: E402

OUT_DIR = ROOT / "examples"
REGRET_ORDER_ID = 6  # delivered order with one item; customer e-mail and product come from the data


def regret_conversation() -> list[str]:
    tables = load_tables()
    order = tables["orders"].set_index("order_id").loc[REGRET_ORDER_ID]
    email = tables["customers"].set_index("customer_id").loc[order.customer_id, "email"]
    items = tables["order_items"].merge(tables["products"][["product_id", "name"]], on="product_id")
    product = items[items.order_id == REGRET_ORDER_ID]["name"].iloc[0]
    return [
        f"Oi! Me arrependi da compra do pedido {REGRET_ORDER_ID} ({product}) e quero devolver. Como faço?",
        f"Meu e-mail é {email}",
        "E se ele apresentar algum defeito, o que eu faço?",
    ]


EXAMPLES = [
    ("01_violoes_ate_1000", "Violões até R$ 1.000", ["Quais opções de violões disponíveis custando até R$1000?"]),
    ("02_endereco_e_horario", "Endereço e horário", ["Qual o endereço da loja e o horário de funcionamento?"]),
    ("03_preco_takamine_gd20", "Preço de um produto", ["Quanto custa o Takamine GD20?"]),
    ("04_arrependimento_pedido_real", "Arrependimento num pedido real", regret_conversation()),
    ("05_fora_do_escopo", "Pergunta fora do escopo", ["Você me ajuda a fazer minha declaração de imposto de renda?"]),
]


def hard_breaks(text: str) -> str:
    return "\n".join(line + "  " for line in text.splitlines())


def run(slug: str, title: str, messages: list[str]) -> Path:
    agent = Agent()
    lines = [
        f"# {title}",
        "",
        f"- Model: `{agent.model}` (reasoning effort: `{agent.reasoning_effort}`)",
        f"- Run at: {datetime.now():%Y-%m-%d %H:%M} (local time)",
        "- Generated by `scripts/run_examples.py`; not edited by hand.",
        "",
    ]
    for message in messages:
        answer = agent.reply(message)
        lines += ["---", "", f"**Cliente:** {message}", ""]
        if agent.trace:
            lines += [f"<details><summary>Tool calls ({len(agent.trace)})</summary>", ""]
            for step in agent.trace:
                result = json.dumps(step["result"], ensure_ascii=False, indent=2)
                lines += [f"`{step['tool']}({step['arguments']})`", "", "```json", result, "```", ""]
            lines += ["</details>", ""]
        lines += ["**Empório:**", "", hard_breaks(answer), ""]
        print(f"[{slug}] Cliente: {message}\n[{slug}] Empório: {answer}\n")
    lines += ["---", "", f"Usage: {agent.usage}", ""]
    path = OUT_DIR / f"{slug}.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    OUT_DIR.mkdir(exist_ok=True)
    only = sys.argv[1:]  # optional slug prefixes, e.g. `python scripts/run_examples.py 04`
    for slug, title, messages in EXAMPLES:
        if not only or slug.startswith(tuple(only)):
            print(f"wrote {run(slug, title, messages).relative_to(ROOT)}")


if __name__ == "__main__":
    main()
